SERVICE_COLUMNS = [
    "id", "is_deleted", "deleted_at", "deleted_by",
    "created_at", "created_by", "updated_at", "updated_by",
    "row_version", "photo_path", "_search_corpus",
]


# =============================================================================
# Подготовка DataFrame к экспорту
# =============================================================================

def prepare_for_export(df: pd.DataFrame, sheet_name: str) -> pd.DataFrame:
    """Готовит DataFrame к экспорту:
    - Убирает служебные колонки.
    - Добавляет "№" (для Закупок, ОС, Пластика).
    - Приводит числовые к float.
    - Устанавливает порядок колонок (как в исходном Excel).
    - NaN → пустые ячейки.
    """
    df = df.copy()

    # 1. Убираем служебные
    df = df.drop(columns=[c for c in SERVICE_COLUMNS if c in df.columns])

    # 2. Приводим числовые к float
    for col in NUMERIC_COLUMNS.get(sheet_name, []):
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")

    # 3. Добавляем "№" (только если колонка "№" есть в COLUMN_ORDER)
    order = COLUMN_ORDER.get(sheet_name, [])
    if "№" in order:
        df = df.reset_index(drop=True)
        df.insert(0, "№", df.index + 1)

    # 4. Порядок колонок
    if order:
        # Колонки из order, которые есть в df
        ordered = [c for c in order if c in df.columns]
        # Плюс остальные (если есть) — в конце
        rest = [c for c in df.columns if c not in ordered]
        df = df[ordered + rest]

    # 5. NaN → пустые ячейки
    df = df.where(pd.notna(df), None)

    return df


# =============================================================================
# Экспорт в .xlsx (bytes)
# =============================================================================

def export_to_excel_bytes(
    dfs: dict[str, pd.DataFrame],
    mapping_sheets: Optional[dict[str, dict[str, str]]] = None,
) -> bytes:
    """Собирает .xlsx с 4 листами.

    :param dfs: {"Закупки": df1, "ОС Главная": df2, ...} — УЖЕ подготовленные
                (через prepare_for_export).
    :param mapping_sheets: опционально — {"Закупки": {eng: rus, ...}, ...}
                           Если передан — добавляется 5-й лист "_mapping".
    :return: bytes (.xlsx)
    """
    buffer = io.BytesIO()

    with pd.ExcelWriter(buffer, engine="openpyxl") as writer:
        for sheet_name, df in dfs.items():
            df.to_excel(writer, sheet_name=sheet_name, index=False)

        # 5-й лист: сопоставление (опционально)
        if mapping_sheets:
            mapping_rows = []
            for sheet_name, mapping in mapping_sheets.items():
                for eng, rus in mapping.items():
                    mapping_rows.append({
                        "Лист": sheet_name,
                        "Колонка в БД (англ.)": eng,
                        "Колонка в Excel (рус.)": rus,
                    })
            if mapping_rows:
                mapping_df = pd.DataFrame(mapping_rows)
                mapping_df.to_excel(writer, sheet_name="_mapping", index=False)

    return buffer.getvalue()